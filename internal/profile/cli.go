package profile

import (
	"flag"
	"fmt"
	"os"
	"strings"
)

const DefaultPasswordEnv = "MEMORY_PROFILE_PASSWORD"

// CLI registers the common trusted-profile flags on a command FlagSet.
type CLI struct {
	fs                      *flag.FlagSet
	name, root, passwordEnv *string
}

// RegisterCLI adds --profile, --profiles-root and --profile-password-env.
func RegisterCLI(fs *flag.FlagSet) *CLI {
	return &CLI{
		fs:          fs,
		name:        fs.String("profile", "", "use an existing trusted profile"),
		root:        fs.String("profiles-root", "data/profiles", "trusted profiles directory"),
		passwordEnv: fs.String("profile-password-env", DefaultPasswordEnv, "environment variable holding the profile password"),
	}
}

// Resolve returns the effective database/audio paths. In profile mode only
// paths generated by the profile manager are accepted; explicit overrides are
// rejected even when they happen to equal those generated paths.
func (c *CLI) Resolve(dbPath, audioDir string) (string, string, error) {
	if c == nil || strings.TrimSpace(*c.name) == "" {
		return dbPath, audioDir, nil
	}
	for _, key := range []string{"db", "audio-dir"} {
		if c.fs.Lookup(key) == nil {
			continue
		}
		found := false
		c.fs.Visit(func(f *flag.Flag) {
			if f.Name == key {
				found = true
			}
		})
		if found {
			return "", "", fmt.Errorf("--%s cannot be used with --profile", key)
		}
	}
	password := os.Getenv(*c.passwordEnv)
	if password == "" {
		return "", "", fmt.Errorf("environment variable %s is required for --profile", *c.passwordEnv)
	}
	manager, err := Open(*c.root)
	if err != nil {
		return "", "", err
	}
	if !manager.Verify(*c.name, password) {
		return "", "", fmt.Errorf("profile: invalid password")
	}
	paths, err := manager.Resolve(*c.name)
	if err != nil {
		return "", "", err
	}
	return paths.Database, paths.Audio, nil
}

// IndexDirectory follows the same trusted profile selection as Resolve. Call
// Resolve first to authenticate; legacy databases get a dedicated sidecar dir.
func (c *CLI) IndexDirectory(dbPath string) (string, error) {
	if c == nil || strings.TrimSpace(*c.name) == "" {
		return dbPath + ".index", nil
	}
	m, err := Open(*c.root)
	if err != nil {
		return "", err
	}
	p, err := m.Resolve(*c.name)
	if err != nil {
		return "", err
	}
	return p.Index, nil
}
